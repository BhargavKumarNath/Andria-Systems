def _real_data_vintage() -> dict:
    """Derive data_vintage from the actual ingested datasets rather than
    hardcoding it -- the previous hardcoded "2024_Q4" / 116,000,000 values
    silently went stale (and were simply wrong) the moment a real ingestion
    covered a different date range or row count."""
    edgar_dir = PROJECT_ROOT / "dataset" / "processed" / "edgar"
    fred_path = PROJECT_ROOT / "dataset" / "processed" / "FRED_preprocess.parquet"
    vintage = {
        "edgar_through": None,
        "fred_through": None,
        "total_filings_processed": None,
        "total_managers": None,
        "total_cusips": None,
        "source": "SEC EDGAR 13F",
    }
    try:
        import duckdb
        if edgar_dir.exists() and any(edgar_dir.rglob("*.parquet")):
            con = duckdb.connect()
            con.execute("SET memory_limit='2GB'")
            row = con.execute(f"""
                SELECT MAX(source_quarter), COUNT(*),
                       COUNT(DISTINCT FILINGMANAGER_NAME), COUNT(DISTINCT CUSIP)
                FROM read_parquet('{edgar_dir}/**/*.parquet', hive_partitioning=true)
            """).fetchone()
            if row:
                vintage["edgar_through"] = row[0]
                vintage["total_filings_processed"] = row[1]
                vintage["total_managers"] = row[2]
                vintage["total_cusips"] = row[3]
            con.close()
        if fred_path.exists():
            con = duckdb.connect()
            fred_max = con.execute(
                f"SELECT MAX(observation_date) FROM read_parquet('{fred_path}')"
            ).fetchone()
            if fred_max:
                vintage["fred_through"] = str(fred_max[0])
            con.close()
    except Exception as exc:
        print(f"  [WARN] could not derive real data_vintage: {exc}")
    return vintage


def _recent_runs(limit: int = 5) -> list[dict]:
    """Recent pipeline runs, read from the real manifest.json each `andria run`
    invocation writes to artifacts/runs/{run_id}/ -- not a fabricated run log."""
    runs_dir = ARTIFACTS / "runs"
    if not runs_dir.exists():
        return []
    manifests = sorted(runs_dir.glob("*/manifest.json"), key=lambda p: p.stat().st_mtime, reverse=True)
    out = []
    for path in manifests[:limit]:
        try:
            m = json.loads(path.read_text())
        except Exception:
            continue
        out.append({
            "run_id": m.get("run_id"),
            "stage": m.get("stage"),
            "status": m.get("status"),
            "started_at": m.get("started_at"),
            "completed_at": m.get("completed_at"),
            "git_sha": m.get("git_sha"),
        })
    return out


def export_metadata(run_id: str) -> None:
    artifact_names = [
        "signals.json", "regimes.json", "clusters.json",
        "portfolio.json", "validation.json", "backtest.json",
    ]
    vintage = _real_data_vintage()
    if vintage["edgar_through"] is None:
        vintage = {
            "edgar_through": "2024_Q4",
            "fred_through": "2024-12-31",
            "total_filings_processed": 116_000_000,
            "source": "SEC EDGAR 13F (2000-2024) [placeholder -- no real ingestion found]",
        }
    _write("metadata.json", {
        "generated_at": datetime.now(UTC).isoformat(),
        "run_id": run_id,
        "git_commit": _git_commit(),
        "pipeline_version": "4.16",
        "data_vintage": vintage,
        "recent_runs": _recent_runs(),
        "artifact_hashes": {n: _file_sha16(n) for n in artifact_names},
    })


# ── demo fallback ─────────────────────────────────────────────────────────────

def _demo_fallback(filename: str, kind: str, run_id: str) -> dict:
    """Return existing demo artifact, or a minimal placeholder."""
    demo_path = OUT_DIR / filename
    if demo_path.exists():
        try:
            data = json.loads(demo_path.read_text())
            data["run_id"] = run_id
            return data
        except Exception:
            pass
    return {
        "generated_at": datetime.now(UTC).isoformat(),
        "run_id": run_id,
        "_note": f"Run 'andria run' then 'python export_static_artifacts.py' to populate {kind} data.",
    }


# ── main ──────────────────────────────────────────────────────────────────────

def main() -> None:
    try:
        from andria.core.config import get_settings
        run_id = get_settings().run_id
    except Exception:
        import uuid
        run_id = datetime.now(UTC).strftime("%Y%m%dT%H%M%S") + "_" + uuid.uuid4().hex[:6]

    print(f"Exporting static artifacts  run_id={run_id}")
    print(f"Output -> {OUT_DIR}")
    if not ARTIFACTS.exists():
        print("  [INFO] No pipeline artifacts found — using demo data.")
    print()

    export_signals(run_id)
    export_regimes(run_id)
    export_clusters(run_id)
    export_portfolio(run_id)
    export_validation(run_id)
    export_backtest(run_id)
    export_metadata(run_id)

    print("\nExport complete.")


if __name__ == "__main__":
    main()
